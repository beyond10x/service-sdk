fn scenario_fixtures_source(paths: &[&str]) -> String {
    if let [path] = paths {
        return format!(
            r#"    let scenarios = [(
        "{path}",
        include_str!("../../conformance/{path}"),
    )];"#
        );
    }
    let fixtures = paths
        .iter()
        .map(|path| {
            format!(
                r#"        (
            "{path}",
            include_str!("../../conformance/{path}"),
        ),"#
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    format!("    let scenarios = [\n{fixtures}\n    ];")
}
